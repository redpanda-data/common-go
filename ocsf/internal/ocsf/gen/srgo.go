package gen

import (
	"fmt"
	"regexp"
	"strconv"
	"strings"
)

// srProtoSuffix is the file suffix shared by all Schema-Registry schema files.
const srProtoSuffix = ".sr.proto"

// SRGoPackageForVersion derives the default Go package name for generated
// .sr.go files from the OCSF version's major component: "1.8.0" → "ocsfv1".
func SRGoPackageForVersion(version string) (string, error) {
	suffix, err := versionToPackage(version)
	if err != nil {
		return "", err
	}
	return "ocsf" + suffix, nil
}

// validGoIdent matches Go identifiers restricted to ASCII, which covers every
// package and message name this generator can produce.
var validGoIdent = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

// EmitSRGo renders the Go source file that embeds one self-contained
// Schema-Registry schema as constants, following the *SRSchema / *SRSubject
// convention of protoc-gen-go-sr-normalize:
//
//	const <msgName>SRSchema  — the exact .sr.proto content, register as-is.
//	const <msgName>SRSubject — the Schema-Registry subject (only when subject
//	                           is non-empty).
//
// The file lands next to the .sr.proto it embeds: same base name, .sr.go
// extension. pkgName is the Go package clause; version is only echoed into
// the generated-file header.
func EmitSRGo(pkgName, version, msgName, subject string, srSchema GeneratedFile) (GeneratedFile, error) {
	if !validGoIdent.MatchString(pkgName) {
		return GeneratedFile{}, fmt.Errorf("ocsf sr-go emit: %q is not a valid Go package name", pkgName)
	}
	if !validGoIdent.MatchString(msgName) {
		return GeneratedFile{}, fmt.Errorf("ocsf sr-go emit: %q is not a valid Go identifier", msgName)
	}
	if err := validateSRSubject(subject); err != nil {
		return GeneratedFile{}, err
	}
	base, ok := strings.CutSuffix(srSchema.Path, srProtoSuffix)
	if !ok {
		return GeneratedFile{}, fmt.Errorf("ocsf sr-go emit: SR schema path %q does not end in %s", srSchema.Path, srProtoSuffix)
	}

	var sb strings.Builder
	sb.WriteString("// Code generated by ocsf-protogen. DO NOT EDIT.\n")
	sb.WriteString("// Source: OCSF schema " + version + "\n\n")
	sb.WriteString("package " + pkgName + "\n\n")
	sb.WriteString("// " + msgName + "SRSchema is the self-contained Schema-Registry proto3 schema for\n")
	sb.WriteString("// the " + msgName + " message (Confluent message-index 0). Register it as-is.\n")
	sb.WriteString("const " + msgName + "SRSchema = " + goStringLiteral(srSchema.Content) + "\n")
	if subject != "" {
		sb.WriteString("\n")
		sb.WriteString("// " + msgName + "SRSubject is the Schema-Registry subject " + msgName + "SRSchema is\n")
		sb.WriteString("// registered under.\n")
		sb.WriteString("const " + msgName + "SRSubject = " + strconv.Quote(subject) + "\n")
	}

	return GeneratedFile{Path: base + ".sr.go", Content: sb.String()}, nil
}

// goStringLiteral renders s as a raw string literal, falling back to an
// interpreted (quoted) literal when s contains a backtick, which raw literals
// cannot escape. Generated .sr.proto content never contains backticks; the
// fallback keeps the emitter total.
func goStringLiteral(s string) string {
	if strings.Contains(s, "`") {
		return strconv.Quote(s)
	}
	return "`" + s + "`"
}
