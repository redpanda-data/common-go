// srProtoFixture is a minimal stand-in for an emitted .sr.proto file.
var srProtoFixture = gen.GeneratedFile{
	Path:    "audit_event.sr.proto",
	Content: "// Code generated by ocsf-protogen. DO NOT EDIT.\n\nsyntax = \"proto3\";\n\npackage ocsf.v1;\n\nmessage AuditEvent {\n  string name = 1;\n}\n",
}

// TestEmitSRGo_WithSubject verifies path, header, package clause, both
// constants, and that the schema text is embedded verbatim in a raw literal.
func TestEmitSRGo_WithSubject(t *testing.T) {
	f, err := gen.EmitSRGo("ocsfv1", "1.8.0", "AuditEvent", "redpanda.ocsf.audit-events-value", srProtoFixture)
	require.NoError(t, err)
	require.Equal(t, "audit_event.sr.go", f.Path)

	require.Contains(t, f.Content, "// Code generated by ocsf-protogen. DO NOT EDIT.\n")
	require.Contains(t, f.Content, "// Source: OCSF schema 1.8.0\n")
	require.Contains(t, f.Content, "package ocsfv1\n")
	require.Contains(t, f.Content, "const AuditEventSRSchema = `"+srProtoFixture.Content+"`\n")
	require.Contains(t, f.Content, `const AuditEventSRSubject = "redpanda.ocsf.audit-events-value"`)

	// Must be valid, already-gofmt-formatted Go.
	formatted, err := format.Source([]byte(f.Content))
	require.NoError(t, err)
	require.Equal(t, string(formatted), f.Content, "emitted .sr.go must already be gofmt-clean")
}

// TestEmitSRGo_NoSubject verifies the subject constant is omitted when no
// subject is configured.
func TestEmitSRGo_NoSubject(t *testing.T) {
	srFile := gen.GeneratedFile{Path: "api_activity.sr.proto", Content: "syntax = \"proto3\";\n"}
	f, err := gen.EmitSRGo("ocsfv1", "1.8.0", "ApiActivity", "", srFile)
	require.NoError(t, err)
	require.Equal(t, "api_activity.sr.go", f.Path)
	require.Contains(t, f.Content, "const ApiActivitySRSchema = `")
	require.NotContains(t, f.Content, "SRSubject")

	formatted, err := format.Source([]byte(f.Content))
	require.NoError(t, err)
	require.Equal(t, string(formatted), f.Content)
}

// TestEmitSRGo_BacktickFallback verifies content containing a backtick falls
// back to an interpreted string literal (raw literals cannot escape one) and
// still round-trips to the exact schema text.
func TestEmitSRGo_BacktickFallback(t *testing.T) {
	srFile := gen.GeneratedFile{Path: "weird.sr.proto", Content: "// a `backtick`\nsyntax = \"proto3\";\n"}
	f, err := gen.EmitSRGo("ocsfv1", "1.8.0", "Weird", "", srFile)
	require.NoError(t, err)
	require.NotContains(t, f.Content, "const WeirdSRSchema = `")
	require.Contains(t, f.Content, `const WeirdSRSchema = "// a `+"`backtick`"+`\nsyntax = \"proto3\";\n"`)

	formatted, err := format.Source([]byte(f.Content))
	require.NoError(t, err)
	require.Equal(t, string(formatted), f.Content)
}

// TestEmitSRGo_InvalidInputs verifies package, message, subject, and path
// validation.
func TestEmitSRGo_InvalidInputs(t *testing.T) {
	_, err := gen.EmitSRGo("not a package", "1.8.0", "AuditEvent", "", srProtoFixture)
	require.ErrorContains(t, err, "package name")

	_, err = gen.EmitSRGo("ocsfv1", "1.8.0", "Not-An-Ident", "", srProtoFixture)
	require.ErrorContains(t, err, "identifier")

	_, err = gen.EmitSRGo("ocsfv1", "1.8.0", "AuditEvent", `bad"subject`, srProtoFixture)
	require.Error(t, err)

	_, err = gen.EmitSRGo("ocsfv1", "1.8.0", "AuditEvent", "", gen.GeneratedFile{Path: "not-an-sr-file.proto"})
	require.ErrorContains(t, err, ".sr.proto")
}

// TestSRGoPackageForVersion verifies the version-derived default package name.
func TestSRGoPackageForVersion(t *testing.T) {
	pkg, err := gen.SRGoPackageForVersion("1.8.0")
	require.NoError(t, err)
	require.Equal(t, "ocsfv1", pkg)

	pkg, err = gen.SRGoPackageForVersion("2.0.0-dev")
	require.NoError(t, err)
	require.Equal(t, "ocsfv2", pkg)

	_, err = gen.SRGoPackageForVersion("not-a-version")
	require.Error(t, err)
}
